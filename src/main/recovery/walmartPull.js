'use strict';
// Walmart payment periods, imported without anyone downloading them
// (owner 2026-11-10: "have the Walmart API automatically include the payment
// periods", on the IMRAN-WORK-PC only). Walmart's Payment Reports API lists
// a reconciliation report per settlement date; each new one goes through the
// SAME importReport a dropped file does, named the way Seller Center names
// its download (…MP_<MMDDYYYY>_…) so the period label, the duplicate guard
// and the archived CSV all come out exactly as for a manual import, and
// every other desktop gets it through the shared folder as usual.
//
// Rules:
//   - only settlements from the last WINDOW_DAYS are looked at, oldest first;
//   - a period already in Recovery (imported by hand, or by an earlier pull)
//     is never replaced, with one exception: a period this module imported
//     itself, while the report is still FRESH_DAYS young, is re-imported if
//     Walmart regenerated the file (Walmart: "the report is regenerated
//     periodically");
//   - a date is only marked done once the import answered, so a failure (no
//     network, an empty returns log) is simply tried again next time.
const fs = require('node:fs');
const crypto = require('node:crypto');

const DAY = 86400000;
// Node's bare network failure reads "fetch failed": say what it means
const plain = (e) => (/fetch failed|ENOTFOUND|ECONNREFUSED|ETIMEDOUT|aborted|timeout/i.test(String(e && e.message)) ? 'Could not reach Walmart (internet down?)' : String((e && e.message) || e));
const WINDOW_DAYS = 120;
const FRESH_DAYS = 4;

// "11072026" -> local midnight Nov 7 2026, or null
function dateOf(s) {
  const m = /^(\d{2})(\d{2})(\d{4})$/.exec(String(s || ''));
  if (!m) return null;
  const d = new Date(Number(m[3]), Number(m[1]) - 1, Number(m[2]));
  return d.getMonth() === Number(m[1]) - 1 ? d : null;
}

function loadState(file) {
  try {
    const s = JSON.parse(fs.readFileSync(file, 'utf8'));
    return { done: {}, ...s, done: (s && s.done) || {} };
  } catch { return { done: {} }; }
}
function saveState(file, st) {
  try { fs.writeFileSync(file, JSON.stringify(st, null, 1)); } catch { /* next pass rewrites it */ }
}

async function pullOnce({ client, importReport, statePath, now = Date.now(), onProgress = () => {} }) {
  const st = loadState(statePath);
  const imported = [];
  const errors = [];
  let checked = 0;
  try {
    const dates = await client.reconReportDates();
    const wanted = dates
      .map((d) => ({ d, t: dateOf(d) }))
      .filter((x) => x.t && now - x.t.getTime() <= WINDOW_DAYS * DAY && x.t.getTime() <= now + DAY)
      .sort((a, b) => a.t - b.t);
    for (const { d, t } of wanted) {
      const prev = st.done[d];
      const fresh = now - t.getTime() < FRESH_DAYS * DAY;
      if (prev && !(fresh && prev.byPull)) continue;
      checked++;
      onProgress(`Reading Walmart's report for ${t.toLocaleDateString()}…`);
      let rep;
      try { rep = await client.reconReport(d); } catch (e) {
        errors.push(`${t.toLocaleDateString()}: ${plain(e)}`);
        if (e.rateLimited) break;
        continue;
      }
      const hash = crypto.createHash('sha256').update(rep.text).digest('hex');
      if (prev && prev.hash === hash) continue; // unchanged since we imported it
      const name = `Walmart_API_MP_${d}_reconciliationreport.csv`;
      try {
        let res = await importReport({ name, text: rep.text, force: false });
        // our own import of this period, regenerated by Walmart since
        if (res && res.alreadyImported && prev && prev.byPull) res = await importReport({ name, text: rep.text, force: true });
        if (res && res.ok) imported.push(res.label);
        const outcome = res && res.ok ? 'imported' : res && res.alreadyImported ? 'already' : res && res.noRefunds ? 'no-refunds' : 'other';
        st.done[d] = { hash, at: now, label: (res && res.label) || '', outcome, byPull: outcome === 'imported' || !!(prev && prev.byPull) };
      } catch (e) {
        errors.push(`${t.toLocaleDateString()}: ${plain(e)}`);
      }
    }
  } catch (e) {
    errors.push(plain(e));
  }
  st.lastCheck = now;
  st.lastError = errors.join(' · ');
  if (imported.length) { st.lastImported = imported; st.lastImportedAt = now; }
  saveState(statePath, st);
  return { ok: errors.length === 0, imported, errors, checked };
}

function status(statePath) {
  const st = loadState(statePath);
  const done = Object.entries(st.done).map(([d, v]) => ({ date: d, ...v })).filter((x) => dateOf(x.date));
  done.sort((a, b) => dateOf(b.date) - dateOf(a.date));
  return {
    lastCheck: st.lastCheck || 0, lastError: st.lastError || '',
    lastImported: st.lastImported || [], lastImportedAt: st.lastImportedAt || 0,
    newest: done[0] || null,
  };
}

module.exports = { pullOnce, status, dateOf, WINDOW_DAYS, FRESH_DAYS };
